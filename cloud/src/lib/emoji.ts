/** Everything the search box can find, one flat list. */
export const ALL_EMOJIS: EmojiEntry[] = EMOJI_SECTIONS.flatMap((section) => section.emojis)

/** Substring search over the keywords — "cry" finds 😢 and 😭. */
export function searchEmojis(term: string, limit = 80): EmojiEntry[] {
  const query = term.trim().toLowerCase()
  if (!query) return []
  const found: EmojiEntry[] = []
  for (const entry of ALL_EMOJIS) {
    if (found.length >= limit) break
    if (entry.keywords.includes(query)) found.push(entry)
  }
  return found
}
