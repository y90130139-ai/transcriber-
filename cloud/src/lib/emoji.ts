/**
 * The emoji shelf (Geno, 2026-10-13; the console's copy, 2026-10-14).
 *
 * Ported row for row from the app's `expo-app-gosian/src/lib/emoji.ts`, so
 * the inbox's picker finds exactly what the phone's does — "cry", "fire",
 * "pray", "skull" — with no keyboard package, no network, and no second
 * search index to drift. Rows are `"emoji keyword keyword"`; the first
 * token is the glyph itself.
 */

export type EmojiEntry = { emoji: string; keywords: string }
export type EmojiSection = { name: string; emojis: EmojiEntry[] }

function sheet(name: string, rows: string[]): EmojiSection {
  return {
    name,
    emojis: rows.map((row) => {
      const [emoji, ...rest] = row.split(' ')
      return { emoji, keywords: rest.join(' ') }
    }),
  }
}

